import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { buildSync } from "esbuild";

import { AUDIO_TYPES } from "../src/features/import/clean-tags.ts";

const IMPORT = path.join(import.meta.dirname, "../src/features/import");
const SOURCE = path.join(IMPORT, "transfer-page-source");
export const TRANSFER_PAGE_OUTPUT = path.join(
  IMPORT,
  "transfer-page.generated.ts",
);

function read(file: string) {
  return readFileSync(path.join(SOURCE, file), "utf8");
}

/** Replaces the one place `tag` appears, and fails if it doesn't. */
function fill(text: string, tag: string, content: string) {
  const parts = text.split(tag);
  if (parts.length !== 2) {
    throw new Error(`Expected "${tag}" once, found ${parts.length - 1}`);
  }
  return parts.join(content);
}

function bundleScript(extensions: string[], logo: string) {
  const { outputFiles } = buildSync({
    absWorkingDir: SOURCE,
    bundle: true,
    define: {
      TRANSFER_EXTENSIONS: JSON.stringify(extensions),
      TRANSFER_LOGO: JSON.stringify(logo),
    },
    entryPoints: ["main.ts"],
    format: "iife",
    minify: true,
    target: "es2018",
    tsconfigRaw: { compilerOptions: { useDefineForClassFields: false } },
    write: false,
  });
  const [script] = outputFiles;
  if (script === undefined) throw new Error("esbuild wrote nothing");
  return script.text.trim();
}

/**
 * The page's real files (`transfer-page-source/`) as one self-contained page,
 * as the source of the module the app imports. See docs/ui.md → Import.
 */
export function buildTransferPage() {
  const extensions = Object.keys(AUDIO_TYPES);
  const logo = `data:image/png;base64,${readFileSync(path.join(SOURCE, "logo.png")).toString("base64")}`;
  const accept = extensions.map((extension) => `.${extension}`).join(",");
  const style = fill(read("style.css"), "./logo.png", logo);
  let page = read("index.html").trim();
  page = fill(page, "__SYNQ_ACCEPT__", accept);
  page = fill(
    page,
    '<link rel="stylesheet" href="./style.css" />',
    `<style>${style}</style>`,
  );
  page = fill(
    page,
    '<script src="./main.ts"></script>',
    `<script>${bundleScript(extensions, logo)}</script>`,
  );
  return `// Generated by scripts/build-transfer-page.ts from ./transfer-page-source.
// Don't edit it: change the source, then run
// \`pnpm build:transfer-page\`.
// prettier-ignore
export const TRANSFER_PAGE = ${JSON.stringify(page)};
`;
}

if (import.meta.main) {
  writeFileSync(TRANSFER_PAGE_OUTPUT, buildTransferPage());
}
