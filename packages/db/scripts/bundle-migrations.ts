/**
 * Inlines drizzle-kit's output (`drizzle/*.sql` + `meta/_journal.json`) into
 * `src/migrations.ts`, in the `{ journal, migrations }` shape that
 * `drizzle-orm/expo-sqlite/migrator` expects.
 *
 * Why not drizzle's documented `migrations.js` (which imports `.sql` files)?
 * That needs `babel-plugin-inline-import` and a Metro `sourceExts` change in
 * the app, and node can't import it in tests. Inlined strings work in both,
 * so the tests run exactly the SQL the app ships.
 *
 * Usage: `node scripts/bundle-migrations.ts [--check]` (`--check` exits 1 if
 * `src/migrations.ts` is stale).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

interface JournalEntry {
  idx: number;
  when: number;
  tag: string;
  breakpoints: boolean;
}

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const drizzleDir = join(packageDir, "drizzle");
const outFile = join(packageDir, "src", "migrations.ts");

function isJournal(value: unknown): value is { entries: JournalEntry[] } {
  return typeof value === "object" && value !== null && "entries" in value;
}

function parseJournal(value: unknown) {
  if (!isJournal(value))
    throw new Error("drizzle/meta/_journal.json has no entries");
  return value;
}

const journal = parseJournal(
  JSON.parse(readFileSync(join(drizzleDir, "meta", "_journal.json"), "utf8")),
);

const entries = journal.entries.map((entry) => {
  const key = `m${entry.idx.toString().padStart(4, "0")}`;
  const sqlText = readFileSync(join(drizzleDir, `${entry.tag}.sql`), "utf8");
  return `    ${key}: ${JSON.stringify(sqlText)},`;
});

const output = `// Generated by scripts/bundle-migrations.ts from drizzle/. Do not edit.
// Regenerate with \`pnpm db:generate\`.

/** Drizzle migrations for library.db, for \`migrate()\` from \`drizzle-orm/expo-sqlite/migrator\`. */
// prettier-ignore
export const libraryMigrations = {
  journal: ${JSON.stringify({ entries: journal.entries }, null, 2).replace(/\n/g, "\n  ")},
  migrations: {
${entries.join("\n")}
  },
};

export default libraryMigrations;
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8");
  if (current !== output) {
    console.error("src/migrations.ts is stale; run `pnpm db:generate`.");
    process.exit(1);
  }
} else {
  writeFileSync(outFile, output);
}
